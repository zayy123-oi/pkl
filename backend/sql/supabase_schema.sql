-- Skema PostgreSQL untuk Supabase, diturunkan dari app/models.py.
-- Aman untuk ditinjau: skrip ini tidak memuat DROP, TRUNCATE, atau data contoh.
-- Terapkan pada database/proyek Supabase yang tepat hanya setelah mencadangkan
-- data dan memastikan belum ada tabel dengan struktur yang berbeda.

CREATE TABLE IF NOT EXISTS tabel_pembimbing (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(50) NOT NULL,
    asal_daerah VARCHAR(50),
    nomer_telepon VARCHAR(15)
);

CREATE TABLE IF NOT EXISTS tabel_lokasi (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(50) NOT NULL,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    radius_meter DOUBLE PRECISION DEFAULT 100.0,
    is_aktif BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS tabel_siswa (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(50) NOT NULL,
    kelas VARCHAR(50) NOT NULL,
    asal_sekolah VARCHAR(50) NOT NULL,
    nomer_telepon VARCHAR(15) NOT NULL,
    nis VARCHAR(20) NOT NULL UNIQUE,
    "startPkl" DATE,
    "endPkl" DATE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    supervisor_id INTEGER REFERENCES tabel_pembimbing(id)
);

CREATE INDEX IF NOT EXISTS ix_tabel_siswa_nis ON tabel_siswa (nis);
CREATE INDEX IF NOT EXISTS ix_tabel_siswa_supervisor_id ON tabel_siswa (supervisor_id);

CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    role VARCHAR(20) NOT NULL,
    student_id INTEGER REFERENCES tabel_siswa(id),
    supervisor_id INTEGER REFERENCES tabel_pembimbing(id),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_users_username ON users (username);

CREATE TABLE IF NOT EXISTS attendances (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL REFERENCES tabel_siswa(id),
    supervisor_id INTEGER REFERENCES tabel_pembimbing(id),
    location_id INTEGER REFERENCES tabel_lokasi(id),
    attendance_date DATE NOT NULL,
    attendance_type VARCHAR(20) NOT NULL,
    attendance_time TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'hadir',
    note TEXT,
    ip_address VARCHAR(45),
    user_agent VARCHAR(500),
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    location_accuracy_meters DOUBLE PRECISION,
    distance_from_target_meters DOUBLE PRECISION,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_attendances_student_id ON attendances (student_id);
CREATE INDEX IF NOT EXISTS ix_attendances_supervisor_id ON attendances (supervisor_id);
CREATE INDEX IF NOT EXISTS ix_attendances_location_id ON attendances (location_id);
CREATE INDEX IF NOT EXISTS ix_attendances_attendance_date ON attendances (attendance_date);
CREATE INDEX IF NOT EXISTS ix_attendances_attendance_type ON attendances (attendance_type);
CREATE INDEX IF NOT EXISTS ix_attendance_student_date_type
    ON attendances (student_id, attendance_date, attendance_type);

CREATE TABLE IF NOT EXISTS tugas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pembimbing INTEGER REFERENCES tabel_pembimbing(id),
    id_siswa INTEGER NOT NULL REFERENCES tabel_siswa(id),
    judul_tugas VARCHAR(150) NOT NULL,
    deskripsi_tugas TEXT,
    deadline TIMESTAMP WITHOUT TIME ZONE,
    "startTugas" TIMESTAMP WITHOUT TIME ZONE,
    status VARCHAR(20) DEFAULT 'pending',
    status_progress VARCHAR(20) DEFAULT 'pending'
);

CREATE INDEX IF NOT EXISTS ix_tugas_id_pembimbing ON tugas (id_pembimbing);
CREATE INDEX IF NOT EXISTS ix_tugas_id_siswa ON tugas (id_siswa);

CREATE TABLE IF NOT EXISTS laporan (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_siswa INTEGER NOT NULL REFERENCES tabel_siswa(id),
    id_tugas INTEGER REFERENCES tugas(id),
    tanggal_laporan DATE DEFAULT CURRENT_DATE,
    isi_laporan TEXT NOT NULL,
    foto_laporan VARCHAR(255),
    status_review VARCHAR(20) DEFAULT 'pending',
    komentar_pembimbing TEXT
);

CREATE INDEX IF NOT EXISTS ix_laporan_id_siswa ON laporan (id_siswa);
CREATE INDEX IF NOT EXISTS ix_laporan_id_tugas ON laporan (id_tugas);
